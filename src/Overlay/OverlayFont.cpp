static const uint8_t* GlyphFor(char character)
{
    int index = (int)(unsigned char)character;

    if (index < OverlayFont::FIRST_PRINTABLE || index > OverlayFont::LAST_PRINTABLE) index = OverlayFont::FIRST_PRINTABLE;

    return OverlayFont::GLYPHS[index - OverlayFont::FIRST_PRINTABLE];
}

int OverlayFont::MeasureWidth(const std::string& text, int scale)
{
    if (text.empty() || scale <= 0) return 0;

    const int advance = (GLYPH_WIDTH + GLYPH_SPACING) * scale;

    return (int)text.size() * advance - GLYPH_SPACING * scale + MARGIN * 2;
}

int OverlayFont::MeasureHeight(int scale)
{
    if (scale <= 0) return 0;

    return GLYPH_HEIGHT * scale + MARGIN * 2;
}

void OverlayFont::Render(const std::string& text, int scale, OverlayFont::Channels channels, OverlayFont::Panel& panel)
{
    panel.width = MeasureWidth(text, scale);
    panel.height = MeasureHeight(scale);

    if (panel.width <= 0 || panel.height <= 0)
    {
        panel.pixels.clear();
        return;
    }

    panel.pixels.assign((size_t)panel.width * (size_t)panel.height * 4, 0);

    const bool blueFirst = channels == OverlayFont::Channels::Bgra;

    for (size_t at = 0; at < panel.pixels.size(); at += 4)
    {
        panel.pixels[at + 0] = blueFirst ? BACKGROUND_BLUE : BACKGROUND_RED;
        panel.pixels[at + 1] = BACKGROUND_GREEN;
        panel.pixels[at + 2] = blueFirst ? BACKGROUND_RED : BACKGROUND_BLUE;
        panel.pixels[at + 3] = BACKGROUND_ALPHA;
    }

    const int advance = (GLYPH_WIDTH + GLYPH_SPACING) * scale;

    for (size_t character = 0; character < text.size(); ++character)
    {
        const uint8_t* glyph = GlyphFor(text[character]);
        const int originX = MARGIN + (int)character * advance;

        for (int row = 0; row < GLYPH_HEIGHT; ++row)
        {
            const uint8_t bits = glyph[row];

            for (int column = 0; column < GLYPH_WIDTH; ++column)
            {
                if ((bits & (1u << (GLYPH_WIDTH - 1 - column))) == 0) continue;

                for (int downscale = 0; downscale < scale; ++downscale)
                {
                    for (int across = 0; across < scale; ++across)
                    {
                        const int x = originX + column * scale + across;
                        const int y = MARGIN + row * scale + downscale;

                        if (x < 0 || x >= panel.width || y < 0 || y >= panel.height) continue;

                        uint8_t* pixel = panel.pixels.data() + ((size_t)y * (size_t)panel.width + (size_t)x) * 4;

                        pixel[0] = blueFirst ? TEXT_BLUE : TEXT_RED;
                        pixel[1] = TEXT_GREEN;
                        pixel[2] = blueFirst ? TEXT_RED : TEXT_BLUE;
                        pixel[3] = 255;
                    }
                }
            }
        }
    }
}

void OverlayFont::Blend(const OverlayFont::Panel& panel, void* destination, int destinationWidth, int destinationHeight,
                        int destinationStride, int left, int top)
{
    if (!destination || panel.pixels.empty()) return;

    uint8_t* target = (uint8_t*)destination;

    for (int row = 0; row < panel.height; ++row)
    {
        const int y = top + row;
        if (y < 0 || y >= destinationHeight) continue;

        for (int column = 0; column < panel.width; ++column)
        {
            const int x = left + column;
            if (x < 0 || x >= destinationWidth) continue;

            const uint8_t* source = panel.pixels.data() + ((size_t)row * (size_t)panel.width + (size_t)column) * 4;
            uint8_t* pixel = target + (size_t)y * (size_t)destinationStride + (size_t)x * 4;

            const uint32_t alpha = source[3];
            if (alpha == 0) continue;

            if (alpha == 255)
            {
                pixel[0] = source[0];
                pixel[1] = source[1];
                pixel[2] = source[2];
                pixel[3] = 255;
                continue;
            }

            const uint32_t inverse = 255 - alpha;

            pixel[0] = (uint8_t)((source[0] * alpha + pixel[0] * inverse) / 255);
            pixel[1] = (uint8_t)((source[1] * alpha + pixel[1] * inverse) / 255);
            pixel[2] = (uint8_t)((source[2] * alpha + pixel[2] * inverse) / 255);
            pixel[3] = 255;
        }
    }
}
