package android.renderscript;

public class Double4
{
    public double x;
    public double y;
    public double z;
    public double w;

    public Double4()
    {
    }

    public Double4(double initX, double initY, double initZ, double initW)
    {
        x = initX;
        y = initY;
        z = initZ;
        w = initW;
    }
}
