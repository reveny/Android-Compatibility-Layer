package android.renderscript;

public class Long4
{
    public long x;
    public long y;
    public long z;
    public long w;

    public Long4()
    {
    }

    public Long4(long initX, long initY, long initZ, long initW)
    {
        x = initX;
        y = initY;
        z = initZ;
        w = initW;
    }
}
