package android.renderscript;

public class Byte4
{
    public byte x;
    public byte y;
    public byte z;
    public byte w;

    public Byte4()
    {
    }

    public Byte4(byte initX, byte initY, byte initZ, byte initW)
    {
        x = initX;
        y = initY;
        z = initZ;
        w = initW;
    }
}
