package android.renderscript;

public class Short4
{
    public short x;
    public short y;
    public short z;
    public short w;

    public Short4()
    {
    }

    public Short4(short initX, short initY, short initZ, short initW)
    {
        x = initX;
        y = initY;
        z = initZ;
        w = initW;
    }
}
