package android.renderscript;

public class Int4
{
    public int x;
    public int y;
    public int z;
    public int w;

    public Int4()
    {
    }

    public Int4(int initX, int initY, int initZ, int initW)
    {
        x = initX;
        y = initY;
        z = initZ;
        w = initW;
    }
}
